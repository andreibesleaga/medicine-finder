// Builds server/data/unii-synonyms.json from the US FDA's UNII names list, so a search finds every
// official name of an ingredient (INN, USAN, BAN, JAN, Latin…), e.g. "levalbuterol" and "levosalbutamol".
//
//   1. Download https://precision.fda.gov/uniisearch/archive/latest/UNIIs.zip (about 20 MB; it holds
//      UNII_Names_<date>.txt). FDA content is in the public domain.
//   2. node scripts/build-unii-synonyms.mjs path/to/UNII_Names_<date>.txt
//   3. Review the diff of server/data/unii-synonyms.json, run npm test, commit.
//
// Only substances with an international nonproprietary name ([INN]) are kept; only official names
// and the standard name lists below; a name that belongs to more than one substance is dropped, so
// two different substances are never joined. Output is sorted, so the same input gives the same file.

import { readFileSync, writeFileSync } from "node:fs";
import { normalize } from "../server/lib/text.js";

const LISTS = new Set(["INN", "USAN", "BAN", "JAN", "WHO-DD", "MART.", "EP MONOGRAPH", "WHO-IP", "WHO-IP LATIN", "USP MONOGRAPH"]);
// plain names only: letters, spaces and hyphens, no codes, no "component" entries
const PLAIN = /^[a-z][a-z -]{2,39}$/;

const file = process.argv[2];
if (!file) {
  console.error("usage: node scripts/build-unii-synonyms.mjs UNII_Names_<date>.txt");
  process.exit(1);
}

const byUnii = new Map(); // unii -> Set(names)
const hasInn = new Set();
const owners = new Map(); // name -> Set(unii)
for (const line of readFileSync(file, "utf8").split("\n").slice(1)) {
  const [raw, type, unii] = line.split("\t");
  if (!unii) continue;
  const tag = /\[([^\]]+)\]\s*$/.exec(raw)?.[1];
  if (tag === "INN") hasInn.add(unii);
  if (type !== "of" && !(type === "cn" && tag && LISTS.has(tag))) continue;
  const name = normalize(raw.replace(/\s*\[[^\]]+\]\s*$/, ""));
  if (!PLAIN.test(name) || /\bcomponent\b/.test(name)) continue;
  if (!byUnii.has(unii)) byUnii.set(unii, new Set());
  byUnii.get(unii).add(name);
  if (!owners.has(name)) owners.set(name, new Set());
  owners.get(name).add(unii);
}

const groups = [];
for (const [unii, names] of byUnii) {
  if (!hasInn.has(unii)) continue;
  const unique = [...names].filter((n) => owners.get(n).size === 1).sort();
  if (unique.length >= 2) groups.push(unique);
}
groups.sort((a, b) => a[0].localeCompare(b[0]));

const out = {
  note: "Generated by scripts/build-unii-synonyms.mjs from the US FDA UNII names list (public domain): official names of one substance (INN, USAN, BAN, JAN, Latin). Do not edit by hand; hand-made groups are in synonyms.json and win over these.",
  source: file.split("/").pop(),
  groups,
};
writeFileSync(new URL("../server/data/unii-synonyms.json", import.meta.url), `${JSON.stringify(out, null, 0).replace(/\],\[/g, "],\n[")}\n`);
console.log(`${groups.length} groups, ${groups.flat().length} names`);
